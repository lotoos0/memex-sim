import assert from 'node:assert/strict';
import { analyze, newResult } from './engine-v2-market-persistence-metrics.mjs';
const result = newResult();
const rows = [[0,.1],[1000,.05],[36000,.85],[37000,.75],[60000,.92],[61000,.81],[1799000,.9]]
  .map(([ms, post], i) => ({ ms, post, quote: 1, side: i % 2 ? 'SELL' : 'BUY' }));
analyze({ token: 'fixture', rows }, result);
assert.equal(result.paths, 1);
assert.equal(result.cells.all.exposure, 1800);
assert.equal(result.cells.all.trades, 7);
assert.equal(result.cells.all.active, 7);
assert.deepEqual(result.bursts, { 1: 1, 2: 3 });
assert.deepEqual(result.gaps, { 22: 1, 34: 1, 1737: 1 });
assert.deepEqual(result.pathStats[0].seriesHistogram, result.bursts);
assert.deepEqual(result.pathStats[0].gapHistogram, result.gaps);
assert.deepEqual(result.pathStats[0].windowHistograms[5], result.windows['5:all']);
assert.equal(result.windows['1:all'][0], 1793);
assert.equal(Object.values(result.windows['5:all']).reduce((a,b) => a+b), 360);
assert.equal(Object.values(result.windows['10:all']).reduce((a,b) => a+b), 180);
assert.equal(result.exactLifecycle['proxy:DORMANT'].trades, 2);
assert.equal(result.progression[.8].retreated, 1);
assert.equal(result.progression[.9].declined120, 1);
assert.equal(result.progression[.8].before.trades, 2);
assert.equal(result.progression[.8].after.trades, 3);
assert.equal(result.cells['progress:0-20'].exposure, 37);
const native = newResult();
analyze({ token: 'native', rows, changes: [[0,'ACTIVE'],[10000,'QUIET'],[35000,'DORMANT'],[36000,'ACTIVE']] }, native);
assert.equal(native.cells['native:ACTIVE'].exposure, 1774);
assert.equal(native.cells['native:QUIET'].exposure, 25);
assert.equal(native.cells['native:DORMANT'].exposure, 1);
assert.equal(native.cells['native:ACTIVE'].active, 7);
const completed = newResult();
analyze({ token: 'completed', rows: [{ ms: 1000, post: 1, quote: 1, side: 'BUY' }], completeMs: 1000 }, completed);
assert.equal(completed.paths, 0);
analyze({ token: 'completed', rows: [{ ms: 2000, post: 1, quote: 1, side: 'BUY' }], completeMs: 2000 }, completed);
assert.equal(completed.cells.all.exposure, 3);
console.log('PASS age/progress exposure, no lookahead, bursts, gaps, aligned windows, crossing exclusion and censoring');
